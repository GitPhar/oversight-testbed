"""Regenerate ledger/brier.md from ledger/bets.jsonl. No network, no keys.

    python3 ledger/brier.py

A bet is scored when it has stated odds before data, a binary outcome decided by
its pre-registered rule, and `scored: true`. Odds are P(the bet's stated event).

Rule 15 (one scored bet per run; CONTEXT.md section 3, steer st-21): a scored bet whose row
names the same run as an earlier scored bet (same program and the same result file, the
same raw data with no new data of its own, or an audit naming it the same run) carries
`secondary_of: <that bet>`. It is excluded from the primary Brier and every table built on
it, and scored with all other rows in the Sensitivity row "all scored bets, secondary
included". A scored bet sharing a result file with an earlier scored bet but carrying no
`secondary_of` is reported as unmarked.
"""
import json
import math
from pathlib import Path

HERE = Path(__file__).resolve().parent
BUCKETS = [(0.0, 0.1), (0.1, 0.2), (0.2, 0.3), (0.3, 0.4), (0.4, 0.5),
           (0.5, 0.6), (0.6, 0.7), (0.7, 0.8), (0.8, 0.9), (0.9, 1.0001)]


def brier(pairs):
    return sum((p - o) ** 2 for p, o in pairs) / len(pairs) if pairs else None


def wilson(k, n, z=1.96):
    if n == 0:
        return None
    ph = k / n
    d = 1 + z * z / n
    c = (ph + z * z / (2 * n)) / d
    h = z * math.sqrt(ph * (1 - ph) / n + z * z / (4 * n * n)) / d
    return max(0.0, c - h), min(1.0, c + h)


def fmt(x, nd=3):
    return "—" if x is None else f"{x:.{nd}f}"


def bucket_label(lo, hi):
    return f"{lo:.1f}–{min(hi, 1.0):.1f}"


def calib_rows(pairs):
    """(mean predicted, wilson lo, wilson hi) for each filled bucket."""
    rows = []
    for lo, hi in BUCKETS:
        cell = [(p, o) for p, o in pairs if lo <= p < hi]
        if cell:
            ci = wilson(sum(o for _, o in cell), len(cell))
            rows.append((sum(p for p, _ in cell) / len(cell), ci[0], ci[1]))
    return rows


def main():
    bets = [json.loads(l) for l in (HERE / "bets.jsonl").read_text().splitlines() if l.strip()]
    scored_all = [b for b in bets if b["scored"]]
    secondary = [b for b in scored_all if b.get("secondary_of")]
    scored = [b for b in scored_all if not b.get("secondary_of")]
    seen, unmarked = {}, []
    for b in scored_all:
        k = (b["program"], b.get("result_file"))
        if k[1] and k in seen and not b.get("secondary_of"):
            unmarked.append(f"{b['id']} (same result file as {seen[k]})")
        seen.setdefault(k, b["id"])
    eng_all = [(b["engine_odds"], b["outcome"]) for b in scored_all]
    hum_all = [(b["human_odds"], b["outcome"]) for b in scored_all if b["human_odds"] is not None]
    eng = [(b["engine_odds"], b["outcome"]) for b in scored]
    hum = [(b["human_odds"], b["outcome"]) for b in scored if b["human_odds"] is not None]
    first = [(b["engine_odds_first"], b["outcome"]) for b in scored]
    n, hits = len(eng), sum(o for _, o in eng)
    base = hits / n
    gm9 = next(b for b in bets if b["id"] == "em-gm9")
    gm1 = next(b for b in scored if b["id"] == "em-gm1")
    sec_by = {}
    for b in secondary:
        sec_by.setdefault(b["secondary_of"], []).append(b["id"])
    alt_gm1 = [(0.30 if b is gm1 else b["engine_odds"], b["outcome"]) for b in scored]
    # Rule 14 (template v2): odds written as prior + adjustment + reason. The prior alone against the adjusted odds,
    # on the same bets, is the published value of the adjustment step.
    pri = [b for b in scored if b.get("odds_prior") is not None]
    pri_alone = [(b["odds_prior"], b["outcome"]) for b in pri]
    pri_adj = [(b["engine_odds"], b["outcome"]) for b in pri]

    L = []
    w = L.append
    w("# Brier score and calibration")
    w("")
    w("Generated by `python3 ledger/brier.py` from `ledger/bets.jsonl`. Do not edit by hand; edit the bets and rerun.")
    w("")
    w("## In plain English")
    w("")
    w(f"Before each test, the engine wrote down how likely it thought a real, rule-passing result was. "
      f"{n} bets have both a stated probability and an outcome decided by their pre-registered rule. "
      f"The engine expected {sum(p for p, _ in eng):.2f} hits and got {hits}.")
    w("")
    be, exp = brier(eng), sum(p for p, _ in eng)
    vs = (f"about the same as a coin ({n} bets cannot tell a gap of {abs(be - 0.25):.3f} from noise)" if abs(be - 0.25) < 0.05
          else ("better than a coin" if be < 0.25 else "worse than a coin"))
    w(f"- **The engine's Brier score is {fmt(be)}.** Lower is better: 0 is perfect, "
      f"0.25 is what always saying 50% scores, and {fmt(brier([(base, o) for _, o in eng]))} is what always saying "
      f"the observed hit rate ({hits}/{n}) would have scored. On this small sample the engine scored {vs}"
      + (", and no better than knowing the hit rate in advance." if be >= brier([(base, o) for _, o in eng]) else "."))
    if secondary:
        ha = sum(o for _, o in eng_all)
        runs = "; ".join(", ".join(v) + " on " + k + "'s run" for k, v in sec_by.items())
        w(f"- **One scored bet per run (rule 15).** {len(secondary)} scored bets re-scored a run an earlier bet was already scored on "
          f"({runs}), so one run's luck counted "
          f"more than once. They are left out of the primary number above. Counting every row as before gives "
          f"**{fmt(brier(eng_all))} on {len(eng_all)} bets** ({ha} hits); both numbers are published, the primary is the one-per-run figure.")
    if unmarked:
        w(f"- **Unmarked repeats of a run:** {', '.join(unmarked)}. Each needs `secondary_of` or a `scoring_note` saying why it is a run of its own.")
    lo_p, hi_p = min(p for p, _ in eng), max(p for p, _ in eng)
    hit_p = sorted({p for p, o in eng if o == 1})
    lean = ("too low" if hits > exp + 0.5 else "too high" if hits < exp - 0.5 else "about right in total")
    w(f"- **Where the odds sat.** Scored bets were given {lo_p:.0%}–{hi_p:.0%}; the hits were bets given "
      f"{', '.join(f'{p:.0%}' for p in hit_p) or 'nothing (no hits)'}. Expected {exp:.2f} hits, observed {hits}: "
      f"on net the odds look {lean}. With {n} bets, none of this is reliable.")
    bf = brier(first)
    w(f"- **Odds as first written down score {fmt(bf)}** against {fmt(be)} for the odds in force at pre-registration. "
      "In the founding week, the overnight literature pass lowered direction 3 from 0.45 to 0.25 (it hit) and lowered "
      "directions 1 and 4 (they missed); later bets have not been revised.")
    covered = all(lo_ci <= pred <= hi_ci for pred, lo_ci, hi_ci in calib_rows(eng))
    w(f"- **{n} bets cannot establish calibration** (H1 needs at least 20, with 4 hits and 4 misses). "
      + ("Every filled bucket's 95% interval includes its predicted value. " if covered
         else "At least one bucket's 95% interval excludes its predicted value. ")
      + "The table is published so the number accrues honestly, not because it says much yet.")
    refs = sorted({b.get("referee") or "model" for b in scored})
    if len(refs) > 1:
        parts = []
        for r in refs:
            pr = [(b["engine_odds"], b["outcome"]) for b in scored if (b.get("referee") or "model") == r]
            parts.append(f"{r}-graded {fmt(brier(pr))} on {len(pr)}")
        w("- **By referee** (what decided the outcome): " + "; ".join(parts) + ". Too few to compare yet (`ARCHITECTURE.md`, referee_test).")
    if pri:
        gap = brier(pri_alone) - brier(pri_adj)
        w(f"- **The adjustment's value (rule 14).** On the {len(pri)} scored bet{'s' if len(pri) != 1 else ''} whose odds were "
          f"written as prior + adjustment, the prior alone (the record's hit rate) scores {fmt(brier(pri_alone))} and the "
          f"adjusted odds {fmt(brier(pri_adj))}: the adjustment "
          + (f"helped by {gap:.3f}." if gap > 0 else f"did not help ({-gap:.3f} worse)." if gap < 0 else "made no difference.")
          + (" Too few bets to tell from noise." if len(pri) < 20 else ""))
    else:
        w("- **The adjustment's value (rule 14) is not measured yet.** From 2026-11-05 every new bet's odds are written as "
          "a prior from `ledger/prior.md` plus an adjustment with a one-line reason; no scored bet carries them yet. "
          "The Sensitivity table scores the prior alone against the adjusted odds as they arrive.")
    if not hum:
        w("- **The human column is empty, honestly.** No scored bet carries Sean's odds: they were not recorded in the founding week, "
          "and later bets were pre-registered with the form blank. Each bet's `human_odds_note` says why.")
    else:
        w(f"- **Sean's odds are scored on {len(hum)} bet{'s' if len(hum) != 1 else ''}:** Brier {fmt(brier(hum))}"
          + (f" ({fmt(brier(hum_all))} on {len(hum_all)} counting secondary bets)." if len(hum_all) != len(hum) else "."))
    w("")
    w("## Scores")
    w("")
    w("| side | bets scored | expected hits | observed hits | Brier | reference: always the base rate | reference: always 0.5 |")
    w("|---|---|---|---|---|---|---|")
    w(f"| engine | {n} | {sum(p for p, _ in eng):.2f} | {hits} | **{fmt(brier(eng))}** | {fmt(brier([(base, o) for _, o in eng]))} | 0.250 |")
    w(f"| human (Sean) | {len(hum)} | — | — | {fmt(brier(hum))} | — | — |")
    if secondary:
        w(f"| engine, all scored bets, secondary included (sensitivity) | {len(eng_all)} | {sum(p for p, _ in eng_all):.2f} | {sum(o for _, o in eng_all)} | {fmt(brier(eng_all))} | {fmt(brier([(sum(o for _, o in eng_all) / len(eng_all), o) for _, o in eng_all]))} | 0.250 |")
    w(f"| engine + human | 0 | — | — | — | — | — |")
    w("")
    w("The base-rate reference uses the observed hit rate, which nobody knew in advance, so it flatters the reference. "
      "Every row but the sensitivity row counts one scored bet per run (rule 15).")
    w("")
    w("## Calibration table (engine)")
    w("")
    w("Predicted = mean stated probability in the bucket; observed = fraction that hit; 95% Wilson interval on the observed fraction.")
    w("")
    w("| odds bucket | bets | predicted | observed | 95% interval | human: bets | human: predicted | human: observed |")
    w("|---|---|---|---|---|---|---|---|")
    for lo, hi in BUCKETS:
        cell = [(p, o) for p, o in eng if lo <= p < hi]
        hcell = [(p, o) for p, o in hum if lo <= p < hi]
        if not cell:
            w(f"| {bucket_label(lo, hi)} | 0 | — | — | — | {len(hcell)} | — | — |")
            continue
        k = sum(o for _, o in cell)
        ci = wilson(k, len(cell))
        w(f"| {bucket_label(lo, hi)} | {len(cell)} | {sum(p for p, _ in cell) / len(cell):.2f} | "
          f"{k}/{len(cell)} = {k / len(cell):.2f} | [{ci[0]:.2f}, {ci[1]:.2f}] | {len(hcell)} | — | — |")
    w("")
    w("## Every scored bet")
    w("")
    w("| bet | direction | event the odds were for | engine odds (first stated) | human odds | outcome | (p − o)² | pre-registration | result |")
    w("|---|---|---|---|---|---|---|---|---|")
    for b in scored_all:
        p, o = b["engine_odds"], b["outcome"]
        sec = f" (secondary of {b['secondary_of']}; sensitivity only)" if b.get("secondary_of") else ""
        w(f"| {b['id']}{sec} | {b['map']} {b['direction']} | {b['odds_event']} | {p:.2f} ({b['engine_odds_first']:.2f}) | "
          f"{'—' if b['human_odds'] is None else b['human_odds']} | {o} | {(p - o) ** 2:.4f} | "
          f"`{b['prereg_commit']}` | `{b['result_file']}` |")
    w("")
    w("## Sensitivity")
    w("")
    w("| variant | bets | engine Brier |")
    w("|---|---|---|")
    w(f"| primary (odds in force at the pre-registration; one scored bet per run, rule 15) | {n} | {fmt(brier(eng))} |")
    w(f"| all scored bets, secondary included (every row counted, as before rule 15) | {len(eng_all)} | {fmt(brier(eng_all))} |")
    w(f"| human (Sean), all scored bets, secondary included | {len(hum_all)} | {fmt(brier(hum_all))} |")
    w(f"| odds as first written down | {n} | {fmt(brier(first))} |")
    w(f"| prior alone (`odds_prior`, the record's hit rate from `ledger/prior.md`), on the bets whose odds carry one (rule 14) | {len(pri)} | {fmt(brier(pri_alone))} |")
    w(f"| adjusted odds (prior + `odds_adjustment`, the engine's odds), on the same bets | {len(pri)} | {fmt(brier(pri_adj))} |")
    w(f"| direction 1 at 0.30 (its 0.15 was committed one minute after its pre-registration; see the bet's note) | {n} | {fmt(brier(alt_gm1))} |")
    w(f"| add direction 9 at {gm9['engine_odds']:.2f}, if its conceptual result is judged publishable | {n + 1} | {fmt(brier(eng + [(gm9['engine_odds'], 1)]))} |")
    w(f"| add direction 9 at {gm9['engine_odds']:.2f}, if it is judged not publishable | {n + 1} | {fmt(brier(eng + [(gm9['engine_odds'], 0)]))} |")
    for sb in [b for b in bets if b.get("sensitivity_outcomes") and b.get("engine_odds") is not None]:
        for o in sb["sensitivity_outcomes"]:
            w(f"| add {sb['id']} ({sb['verdict']}) at {sb['engine_odds']:.2f}, counted as {'a hit' if o else 'a miss'} | {n + 1} | {fmt(brier(eng + [(sb['engine_odds'], o)]))} |")
    w("")
    w("## What is not scored, and why")
    w("")
    unscored = [b for b in bets if not b["scored"]]
    w(f"{len(unscored)} of the {len(bets)} bets in the ledger are not scored:")
    w("")
    for b in unscored:
        w(f"- **{b['id']}** ({b.get('title', '?')}): {b.get('scoring_note') or '(no scoring_note in this ledger row; the bet owner should add one)'}")
    w("")
    audited = [b for b in bets if b.get("audit_path")]
    reversed_ = [b for b in audited if b.get("verdict_stands") is False]
    sa = [b for b in scored if b.get("audit_path")]
    w(f"{len(audited)} of the {len(bets)} bets have an audit in `ledger/audits/`; {len(sa)} of the {n} scored bets are audited, "
      f"and the audit reversed {len(reversed_)} verdict{'s' if len(reversed_) != 1 else ''}"
      + (": " + "; ".join(f"{b['id']} → {b['verdict']}" for b in reversed_) if reversed_ else "")
      + ". Founding-week (round 1) audits are links into `programs/entangled-mind/audits/` (`ledger/audits/em-*.md`, summary `SUMMARY-1.md`); round 2 is `SUMMARY-2.md`. "
      "When an audit overturns a verdict, the outcome here changes and the change is logged in the bet's `scoring_note`.")
    (HERE / "brier.md").write_text("\n".join(L) + "\n")
    print(f"engine Brier {fmt(brier(eng))} on {n} bets; human {fmt(brier(hum))} on {len(hum)}")


if __name__ == "__main__":
    main()
