#!/usr/bin/env python3
"""Render ledger/steers.md from ledger/steer-values.jsonl and ledger/steers.jsonl (operators/steers.md).

    python3 ledger/steer_values.py            # writes ledger/steers.md
    python3 ledger/steer_values.py --stdout   # prints it instead

The latest line per steer id in steer-values.jsonl is the current valuation. A steer in steers.jsonl with no
valuation is listed as not yet scored and counts in Y, not in X. No network, no keys, no paid calls.
"""
import json
import sys
from collections import Counter, OrderedDict
from pathlib import Path

HERE = Path(__file__).resolve().parent
LABELS = ("helped", "neutral", "hurt")


def read_jsonl(p):
    out = []
    for line in p.read_text().splitlines():
        line = line.strip()
        if line:
            out.append(json.loads(line))
    return out


def load():
    steers = read_jsonl(HERE / "steers.jsonl")
    values = read_jsonl(HERE / "steer-values.jsonl") if (HERE / "steer-values.jsonl").exists() else []
    current = OrderedDict()
    for v in values:                      # later lines win: the latest valuation per steer is current
        current[v["steer_id"]] = v
    return steers, current


def summary(steers, current):
    ids = [s["id"] for s in steers]
    c = Counter(current[i]["value"] for i in ids if i in current)
    unscored = [i for i in ids if i not in current]
    return ids, c, unscored


def render(steers, current):
    ids, c, unscored = summary(steers, current)
    y = len(ids)
    x = c.get("helped", 0)
    strength = Counter(current[i].get("evidence_strength") for i in ids if i in current)
    scorers = sorted({current[i].get("scored_by", "") for i in ids if i in current})
    dates = sorted({current[i].get("scored_at", "") for i in ids if i in current})
    lines = []
    lines.append("# Steers, valued")
    lines.append("")
    lines.append("Generated by `python3 ledger/steer_values.py` from `ledger/steer-values.jsonl` and `ledger/steers.jsonl`. "
                 "Do not edit by hand; edit the valuations and rerun. The method is `operators/steers.md`.")
    lines.append("")
    lines.append("## In plain English")
    lines.append("")
    lines.append(f"**Helped {x} of {y}.** Of the {y} steers Sean has made, a scoring session read what each one changed in the record, "
                 f"what the engine would have done without it, and any number that shows the difference, and labelled it: "
                 f"**{c.get('helped', 0)} helped**, **{c.get('neutral', 0)} neutral**, **{c.get('hurt', 0)} hurt**"
                 + (f", **{len(unscored)} not yet scored**" if unscored else "") + ".")
    lines.append("")
    lines.append(f"The scorer is a Claude session ({'; '.join(s for s in scorers if s)}), scored on {', '.join(d for d in dates if d)}. "
                 "It did not write any of the steers. The method is published so a reader can disagree, and a reader who does files "
                 "a new line under `operators/steers.md`, How to disagree. Every label is re-scored monthly. "
                 f"Evidence behind the labels: {strength.get('measured', 0)} decided by a number in the ledger, "
                 f"{strength.get('traced', 0)} by a chain of named files, {strength.get('early', 0)} given early on a steer whose effect is mostly still to come.")
    lines.append("")
    lines.append("A label is a reading of the record against the default the record shows, not a controlled comparison and not a judgment of Sean. "
                 "The one measurement of his judgment the ledger has is the human column of `ledger/brier.md`; the odds steer below (st-18) is scored by that column's own rule.")
    lines.append("")
    lines.append("## Every steer")
    lines.append("")
    lines.append("| steer | date | what Sean decided, in short | label | why, in one line | evidence |")
    lines.append("|---|---|---|---|---|---|")
    bys = {s["id"]: s for s in steers}
    for i in ids:
        s = bys[i]
        if i in current:
            v = current[i]
            lines.append(f"| {i} | {s.get('date', '')} | {v['steer_in_short']} | **{v['value']}** | {v['reason']} | {v.get('evidence_strength', '')} |")
        else:
            short = (s.get("words") or s.get("reason") or "")[:140]
            lines.append(f"| {i} | {s.get('date', '')} | {short} | not yet scored | logged after the last scoring pass; scored at the next one | — |")
    lines.append("")
    lines.append("## What each steer changed, and the counterfactual")
    lines.append("")
    for i in ids:
        if i not in current:
            continue
        v = current[i]
        lines.append(f"### {i}: {v['steer_in_short']}")
        lines.append("")
        lines.append("- **Changed in the record:** " + "; ".join(v.get("changed") or []) + ".")
        lines.append(f"- **Without it:** {v['counterfactual']} (shown by {v.get('counterfactual_file') or 'no recorded default'}.)")
        lines.append(f"- **Measurable effect:** {v['effect'] or 'none recorded.'}")
        lines.append(f"- **Label:** {v['value']} ({v.get('evidence_strength', '')}). {v['reason']}")
        if v.get("history"):
            lines.append(f"- **Earlier valuations:** {len(v['history'])} (kept in the jsonl).")
        lines.append("")
    return "\n".join(lines) + "\n"


def main():
    steers, current = load()
    md = render(steers, current)
    if "--stdout" in sys.argv:
        sys.stdout.write(md)
    else:
        (HERE / "steers.md").write_text(md)
        ids, c, unscored = summary(steers, current)
        print(f"ledger/steers.md written: helped {c.get('helped', 0)} of {len(ids)} "
              f"({c.get('neutral', 0)} neutral, {c.get('hurt', 0)} hurt, {len(unscored)} not yet scored)")


if __name__ == "__main__":
    main()
