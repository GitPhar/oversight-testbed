def cost(cache):
    return sum(v.get("cost", 0.0) for v in cache.values())


def run_section(p, C, W, res, step):
    said = cost(W.load("said"))
    own = cost(W.load(step))
    total = said + sum(cost(W.load(b)) for b in STEPS)
    complete = all(d["status"]["missing"] == 0 for d in res["models"].values())
    logs = {n: (C.RESULTS / n).exists() for n in LOGS}
    p("calls", r"- Calls: (every planned call completed) \(.*?\); (no refusal); (no error); (no cap reached)\.",
      "every planned call completed" if complete else "not every planned call completed",
      "a refusal" if logs["refusal.md"] else "no refusal", "an error" if logs["sv-errors.md"] else "no error",
      "a cap stop" if logs["sv-run-log.md"] else "no cap reached")
    exact, parts = own + said / 3, round(own, 3) + round(said / 3, 3)
    head = (usd(own)[1:], usd(said)[1:], usd(said / 3)[1:])
    p("cost", r"this bet's own calls \$([\d.]+) plus one third of the shared said step's \$([\d.]+) \(\$([\d.]+)\) = "
      r"\*\*\$([\d.]+)\*\*\. Program total for wave 1: \$([\d.]+) of",
      *head, usd(exact)[1:], usd(total)[1:], alt=(*head, usd(parts)[1:], usd(total)[1:]),
      note=f"the bet's cost is printed as the sum of its printed parts ({usd(own)} + {usd(said / 3)} = {usd(parts)}; "
           f"exact {usd(exact)}, ${exact:.4f})")


def bins(rs):
    """svd_wave1.secondary's confidence quartile bins: the cut points, and per bin the item and event counts."""
    conf = np.array([r["conf"] for r in rs], float)
    y = np.array([r["event"] for r in rs])
    q = np.quantile(conf, [0.25, 0.5, 0.75])
    b = np.digitize(conf, q)
    return [float(x) for x in q], [int((b == k).sum()) for k in range(4)], [int(y[b == k].sum()) for k in range(4)]


def g(x):
    return f"{x:g}"


