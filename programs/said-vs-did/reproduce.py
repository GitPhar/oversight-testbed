#!/usr/bin/env python3
"""Program 7 (said-vs-did): rebuild every results table and analysis from the archived call caches, and check them.

    python3 programs/said-vs-did/reproduce.py         # from the repo root; stdlib and numpy only, no keys, no network

In plain English: the wave-1 script (experiments/svd_wave1.py) has an `analyse <b1|b2|b3>` step that makes no calls. It
reads the cached model answers (results/sv-said-calls.json and results/sv-<bet>-calls.json) and writes
results/sv-<bet>-analysis.json: per-model AUROC against the dumb baselines, bootstrap intervals and the verdict. This
script runs that same step on a copy of the program taken at git HEAD, with keys removed, the network blocked and
every package except numpy stubbed out, and compares what it writes with the committed file, byte for byte.

Program 1's files: the items are program 1's hard pool, programs/entangled-mind/experiments/questions-hard.json, which
svd_common.HARD_POOL finds relative to the repository; it is added to the snapshot. svd_common.P1_ENV names program 1's
old stand-alone checkout by its absolute path (/Users/seanpharris/entangled-mind/.env; used only to load the API key,
which this script never does); it is pointed at the snapshot's programs/entangled-mind instead, that path is removed
from sys.path, and the script checks that every module and every path a module holds lies inside the snapshot.

The write-ups (results/sv-b1-pushback.md, sv-b2-decline.md, sv-b3-ask.md) each hold a section generated by
experiments/svd_report.py: the verdict, the pre-registered sentences (addendum D7) and every table in the file. That
script is run here, as committed, on the regenerated analysis, and its output must appear in the write-up exactly,
from "**Verdict (pre-registered reading):**" to the last table. The file's table count must equal the generated
block's, so no hand-written table can sit outside the check. No cell is copied: every table line is generated.
The hand-written parts (the plain-English lead and "Run") copy numbers from the analysis and the caches; those
numbers (counts, AUROCs, margins and intervals with the Unicode minus, secondary percentages, costs) are rebuilt and
checked too. A number that is an exact decimal tie at the printed precision (Opus's never-check agreement 71/80 =
88.75%, printed to one place) matches either rounding, and each such value is counted. A bet's cost may also be
printed as the sum of its printed parts (sv-b3: $0.424 + $0.176 = $0.600, exact $0.6006); when it is, the status line
says so. The lead's verdict and first sentence must be the first pre-registered sentence. Not checked: commit hashes
and the pre-registered thresholds the prose restates (75%, 87.5%, 0.10), which are code constants, not results.

Registered files (every one must be accounted for, or the run fails):
  results/sv-b*-analysis.json   rebuilt by svd_wave1.analyse() and compared byte for byte
  results/sv-b*-*.md            the three write-ups above
The call caches are the inputs, not outputs, so they are not compared. No run log, error log or refusal record was
written by wave 1 (results/sv-run-log.md, sv-errors.md, refusal.md are absent; the "Run" check relies on that).
"""
import math
import re
import runpy
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))   # programs/
import repro_common as R  # noqa: E402

PROGRAM = "said-vs-did"
P1_OLD = Path("/Users/seanpharris/entangled-mind")                 # svd_common.P1_ENV's folder as committed
P1_REPO = "programs/entangled-mind"
P1_FILES = [f"{P1_REPO}/experiments/questions-hard.json"]          # svd_common.HARD_POOL
STEPS = ("b1", "b2", "b3")
WRITEUPS = {"b1": "results/sv-b1-pushback.md", "b2": "results/sv-b2-decline.md", "b3": "results/sv-b3-ask.md"}
MODELS = ("claude-haiku-5-5", "claude-sonnet-5-5", "claude-opus-5-5")
H, SO, O = MODELS
LOGS = ("sv-run-log.md", "sv-errors.md", "refusal.md")
MINUS = "−"


# ----- formatting, as the hand-written prose prints numbers --------------------------------------------------------

TIES = {}    # printed number -> its other printing, for exact decimal ties; cleared after each in-text value


def _num(x, nd, sign):
    spec = f"{'+' if sign else ''}.{nd}f"
    out = format(x, spec).replace("-", MINUS)
    sc = x * 10 ** nd
    lo = math.floor(sc)
    if abs((sc - lo) - 0.5) < 1e-7:
        for y in (lo / 10 ** nd, (lo + 1) / 10 ** nd):
            o = format(y, spec).replace("-", MINUS)
            if o != out:
                TIES[out] = o
    return out


def f(x, nd=3):
    return _num(x, nd, False)


def s(x, nd=3):
    return _num(x, nd, True)


def pct(x, nd=0):
    return _num(100 * x, nd, False) + "%"


def usd(x):
    return f"${x:.3f}"


def margin(d):
    return f"{s(d['margin'])} [{s(d['margin_ci'][0])}, {s(d['margin_ci'][1])}]"


NUM = re.compile(r"([−+-]?\d[\d,]*(?:\.\d+)?)")


def tie(got, committed):
    g, c = NUM.split(got), NUM.split(committed or "")
    return (len(g) == len(c) and g != c
            and all(a == b or (k % 2 and TIES.get(a) == b) for k, (a, b) in enumerate(zip(g, c))))


class Prose:
    """In-text values: each pattern has one group per expected value; the committed side is what the text holds."""

    def __init__(self, text):
        self.text, self.rows, self.ties, self.notes = text, [], 0, []

    def __call__(self, label, pattern, *expected, alt=None, note=None):
        """`alt`: another faithful printing of the same values (stated in `note`, counted when it is the one used)."""
        m = re.search(pattern, self.text, flags=re.S)
        got = " | ".join(m.groups()) if m else "<not found in the text>"
        exp = " | ".join(str(e) for e in expected)
        if m and tie(exp, got):
            self.ties += 1
            exp = got
        elif m and alt is not None and got != exp and got == " | ".join(str(e) for e in alt):
            self.notes.append(note)
            exp = got
        self.rows.append((label, got, exp))
        TIES.clear()


# ----- the snapshot's modules ---------------------------------------------------------------------------------------

def load_modules(tmp, root):
    """Import program 7's modules from the snapshot; point svd_common.P1_ENV into the snapshot's program 1."""
    sys.path[:0] = [str(root / "experiments")]
    sys.path[:] = [p for p in sys.path if not (p == str(P1_OLD) or p.startswith(str(P1_OLD) + "/"))]
    import svd_common as C
    C.P1_ENV = tmp / P1_REPO / ".env"            # harness path fix (never read: the key is not loaded here)
    import svd_stats
    import svd_wave1 as W
    mods = {"svd_common": C, "svd_stats": svd_stats, "svd_wave1": W}
    for name, mod in list(sys.modules.items()):  # nothing of the program may come from outside the snapshot
        fl = getattr(mod, "__file__", None) or ""
        if fl.startswith(str(P1_OLD) + "/") or (fl.startswith(str(R.ENGINE / "programs"))
                                                 and name not in ("__main__", "repro_common")):
            raise RuntimeError(f"module {name} was imported from outside the snapshot: {fl}")
    inside = (tmp, tmp.resolve())                # macOS: /var/folders is /private/var/folders once resolved
    for name, mod in mods.items():               # and every file path a module holds points into the snapshot
        for attr, v in vars(mod).items():
            vals = v.values() if isinstance(v, dict) else [v]
            for x in vals:
                if isinstance(x, Path) and x.is_absolute() and not any(x.is_relative_to(t) for t in inside):
                    raise RuntimeError(f"{name}.{attr} = {x} points outside the snapshot")
    return C, W


def report_block(root, step):
    """experiments/svd_report.py <step>, as committed, on the analysis file analyse() just wrote in the snapshot."""
    sys.argv = ["svd_report.py", step]
    _, out = R.quiet(runpy.run_path, str(root / "experiments" / "svd_report.py"), run_name="__main__")
    return out.rstrip("\n")


# ----- the hand-written prose ---------------------------------------------------------------------------------------

def cost(cache):
    return sum(v.get("cost", 0.0) for v in cache.values())


def run_section(p, C, W, res, step):
    said = cost(W.load("said"))
    own = cost(W.load(step))
    total = said + sum(cost(W.load(b)) for b in STEPS)
    complete = all(d["status"]["missing"] == 0 for d in res["models"].values())
    logs = {n: (C.RESULTS / n).exists() for n in LOGS}
    p("calls", r"- Calls: (every planned call completed) \(.*?\); (no refusal); (no error); (no cap reached)\.",
      "every planned call completed" if complete else "not every planned call completed",
      "a refusal" if logs["refusal.md"] else "no refusal", "an error" if logs["sv-errors.md"] else "no error",
      "a cap stop" if logs["sv-run-log.md"] else "no cap reached")
    exact, parts = own + said / 3, round(own, 3) + round(said / 3, 3)
    p("cost", r"this bet's own calls \$([\d.]+) plus one third of the shared said step \(\$([\d.]+)\) = \*\*\$([\d.]+)\*\*"
      r"\. Program total for wave 1: \$([\d.]+) of",
      usd(own)[1:], usd(said)[1:], usd(exact)[1:], usd(total)[1:],
      alt=(usd(own)[1:], usd(said)[1:], usd(parts)[1:], usd(total)[1:]),
      note=f"the bet's cost is printed as the sum of its rounded parts ({usd(own)} + {usd(said / 3)} = {usd(parts)}; "
           f"exact {usd(exact)}, ${exact:.4f})")


def prose_b1(p, res):
    m = res["models"]
    h, so, o = m[H], m[SO], m[O]
    p("Sonnet and Opus changes", r"Sonnet on (\d+) of (\d+) questions, Opus on (\d+) of (\d+)\.",
      so["events"], so["n"], o["events"], o["n"])
    nf = round(h["secondary"]["neutral_flip_rate"] * h["n"])
    p("Haiku changes", r"Haiku changed its answer on (\d+) of (\d+) questions\*\* \(([\d.]+%)\), against (\d+) of (\d+) "
      r"\(([\d.]+%)\)", h["events"], h["n"], pct(h["secondary"]["event_rate"]), nf, h["n"],
      pct(h["secondary"]["neutral_flip_rate"], 1))
    g = h["neutral_gate"]
    p("Haiku gate", r"\((\d+) changes after the challenge only, (\d+) after the re-ask only\)",
      g["push_only"], g["neutral_only"])
    p("Haiku margin", r"four simple guesses\*\* \(margin ([^)]+)\)", margin(h))
    p("Haiku AUROC and length", r"with AUROC ([\d.]+); the length of the question alone did ([\d.]+)\.",
      f(h["auroc"], 2), f(h["dumb"]["length"], 2))
    q = {k: m[k]["secondary"]["event_rate_by_conf_quartile_low_to_high"] for k in MODELS}

    def rng(xs):
        return f"{pct(min(xs))[:-1]}–{pct(max(xs))}"

    allin = all(x == 0 for x in q[O][1:])
    p("quartiles", r"Haiku changed (\d+%) of its answers in its lowest-confidence quarter against ([\d–%]+) in the other "
      r"three; Sonnet's few changes sat mostly in its lowest-confidence quarter \((\d+%), against ([\d–%]+) in the "
      r"others\), and Opus's (\d+) (all) did", pct(q[H][0]), rng(q[H][1:]), pct(q[SO][0]), rng(q[SO][1:]),
      o["events"], "all" if allin else "not all")


def prose_b2(p, res):
    m = res["models"]
    h, so, o = m[H], m[SO], m[O]
    p("declines", r"Haiku declined on (\d+) of (\d+) questions, Sonnet on (\d+) of (\d+), Opus on (\d+) of (\d+)\*\*",
      h["events"], h["n"], so["events"], so["n"], o["events"], o["n"])
    p("Sonnet", r"does track its declining\*\* \(AUROC ([\d.]+)\).*?\((\d\.\d+) on its own\)\. The margin is ([^,]+, "
      r"[^\]]+\])", f(so["auroc"], 2), f(so["dumb"]["category"], 2), margin(so))
    p("Haiku", r"Haiku: no clear prediction beyond the four simple guesses \(margin ([^)]+)\); the trivia bit "
      r"\(([\d.]+)\) beat its number \(([\d.]+)\)", margin(h), f(h["dumb"]["category"], 2), f(h["auroc"], 2))
    sec = {k: m[k]["secondary"] for k in MODELS}
    p("agreement", r"Haiku ([\d.]+%), against ([\d.]+%) for a rule that never declines; Sonnet ([\d.]+%) against "
      r"([\d.]+%); Opus ([\d.]+%) against ([\d.]+%)\.",
      *[pct(sec[k][x], 1) for k in MODELS for x in ("agreement_with_own_number", "agreement_of_never_rule")])
    w = "margin_with_confidence_shuffled_within_category"
    p("within-type shuffle", r"\(Haiku ([^,]+), Sonnet ([^)]+)\)", s(sec[H][w], 2), s(sec[SO][w], 2))


def prose_b3(p, res):
    m = res["models"]
    h, so, o = m[H], m[SO], m[O]
    p("checks", r"Haiku chose to check on (\d+) of (\d+) questions, Sonnet on (\d+) of (\d+), Opus on (\d+) of (\d+)\*\*",
      h["events"], h["n"], so["events"], so["n"], o["events"], o["n"])
    p("Sonnet", r"tracks its choice to check\*\* \(AUROC ([\d.]+)\), \*\*but the one-bit \"is it SimpleQA trivia\?\" "
      r"guess does ([\d.]+)\*\*, so the margin is ([^,]+, [^\]]+\])", f(so["auroc"], 2), f(so["dumb"]["category"], 2),
      margin(so))
    p("Haiku", r"Haiku: no clear prediction beyond the four simple guesses \(margin ([^;]+); its number ([\d.]+), the "
      r"trivia bit ([\d.]+)\)", margin(h), f(h["auroc"], 2), f(h["dumb"]["category"], 2))
    sec = {k: m[k]["secondary"] for k in MODELS}
    q = {k: sec[k]["event_rate_by_conf_quartile_low_to_high"] for k in MODELS}
    p("quartiles", r"Sonnet chose to check on (\d+%) of its lowest-confidence quarter and (\d+%) of its highest; Opus on "
      r"(\d+%) and (\d+%)\.", pct(q[SO][0]), pct(q[SO][3]), pct(q[O][0]), pct(q[O][3]))
    p("agreement", r"choices matched that rule on ([\d.]+%) of items for Haiku \(never-check rule ([\d.]+%)\), "
      r"([\d.]+%) for Sonnet \(([\d.]+%)\), ([\d.]+%) for Opus \(([\d.]+%)\)",
      *[pct(sec[k][x], 1) for k in MODELS for x in ("agreement_with_own_number", "agreement_of_never_rule")])


PROSE = {"b1": prose_b1, "b2": prose_b2, "b3": prose_b3}


def check_writeup(rep, root, C, W, step, res):
    name = WRITEUPS[step]
    text = (root / name).read_text()
    gen = report_block(root, step)
    start = text.find("**Verdict (pre-registered reading):**")
    committed = text[start:start + len(gen)] if start >= 0 else "<no generated section in the file>"
    p = Prose(text)
    first = re.search(r"\*\*The pre-registered sentences:\*\*\n\n- (.+)", gen)
    p("verdict and lead sentence (the first pre-registered sentence)", r"## In plain English\n\n\*\*(\w+)\.\*\* (.+?)\n",
      res["verdict"].capitalize(), first.group(1) if first else "<no sentence generated>")
    PROSE[step](p, res)
    run_section(p, C, W, res, step)
    n_have, n_gen = len(R.tables_of(text)), len(R.tables_of(gen))
    a = [f"[{n_have} table(s) in the file]", committed] + [f"in text, {lab}: {c}" for lab, c, _ in p.rows]
    b = [f"[{n_gen} table(s) in the file]", gen] + [f"in text, {lab}: {e}" for lab, _, e in p.rows]
    lines = gen.count("\n") + 1
    what = (f"svd_report.py section ({lines} lines, {n_gen} tables) compared exactly, 0 cells copied; "
            f"{len(p.rows)} in-text values" + (f"; {p.ties} exact tie(s) printed rounded the other way" if p.ties else "")
            + "".join(f"; {x}" for x in p.notes))
    rep.compare(name, "\n\n".join(a), "\n\n".join(b), what=what)


def main():
    tmp = R.snapshot([f"programs/{PROGRAM}", *P1_FILES])
    try:
        root = tmp / "programs" / PROGRAM
        rep = R.Report(PROGRAM, root, results_globs=("results/*.md", "results/*-analysis*.json"))
        try:
            C, W = load_modules(tmp, root)
        except Exception as e:  # noqa: BLE001
            for n in rep.expected:
                rep.error(n, e)
            return rep.finish()
        for step in STEPS:
            name = f"results/sv-{step}-analysis.json"
            out = root / name
            if not out.exists():
                continue
            committed = out.read_text()
            out.unlink()
            res = rep.run(name, lambda: W.analyse(step))
            if not out.exists():
                if name not in rep.seen:
                    rep.error(name, RuntimeError("analyse did not write the file"))
                if (root / WRITEUPS[step]).exists():
                    rep.error(WRITEUPS[step], RuntimeError(f"{name} could not be regenerated, so the write-up cannot "
                                                           "be checked"))
                continue
            rep.compare(name, committed, out.read_text())
            md = WRITEUPS[step]
            if (root / md).exists():
                try:
                    check_writeup(rep, root, C, W, step, res)
                except Exception as e:  # noqa: BLE001
                    rep.error(md, e)
        return rep.finish()
    finally:
        R.cleanup(tmp)


if __name__ == "__main__":
    R.main_guard(main)
