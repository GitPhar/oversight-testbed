// map/<program>.json, or one file holding {programs:[...]}
export async function loadMaps() {
  const m = await manifest();
  const names = (m.map && m.map.length ? m.map : FALLBACK_MAPS).filter((n) => n.endsWith(".json"));
  const got = await Promise.all(names.map((n) => getJSON(DATA + "map/" + n)));
  const programs = [];
  got.forEach((g, i) => {
    if (!g) return;
    const list = Array.isArray(g.programs) ? g.programs : [g];
    for (const p of list) programs.push(normProgram(p, names[i].replace(/\.json$/, "")));
  });
  // "Program 1: …", "Program 2: …" in that order, whatever the file names
  const n = (p) => { const m = String(p.title).match(/program\s*(\d+)/i); return m ? +m[1] : 99; };
  return programs.sort((a, b) => n(a) - n(b));
}

// A short label that is only the title cut off mid-word ("ss-b1: Post-cutoff Brier beats a co") is dropped for the
// title without its trailing parenthesis, which the map wraps at word boundaries.
function cleanLabel(short, title) {
  if (!short) return null;
  const bare = String(short).replace(/^[\w.-]+:\s*/, "").trimEnd();
  const truncated = bare.length < title.length && title.startsWith(bare);
  return truncated ? title.replace(/\s*\([^)]*\)\s*$/, "") : short;
}

function normProgram(p, fallbackId) {
  const dirs = p.directions || p.nodes || p.map || [];
  return {
    raw: p,
    id: p.program || p.id || fallbackId,
    title: p.title || p.name || p.program || fallbackId,
    seed: p.seed_question || p.question || p.seed || "",
    seedDate: p.seed_date || p.opened || "",
    directions: dirs.map((d) => ({
      raw: d,
      id: String(d.id ?? d.direction ?? d.title),
      parent: d.parent ?? d.parent_id ?? d.from ?? null,
      title: d.title || d.label || d.name || d.assumption_at_stake || String(d.id),
      label: cleanLabel(d.short || d.label || null, d.title || ""),
      status: normStatus(d.status ?? d.verdict ?? d.state),
      engine: num(d.engine_odds ?? d.engine_p ?? d.odds ?? d.p),
      human: num(d.human_odds ?? d.human_p),
      cost: d.cost || d.cheapest_test_cost || "",
      test: d.cheapest_test || d.test || "",
      diagnosis: d.diagnosis || "",
      result: d.result || "",
      opened: d.opened || d.created || d.date_opened || "",
      resolved: d.resolved || d.closed || d.date_resolved || "",
      // Rule 13: the map node's own Prior work line (open directions) and novelty (landed or mixed ones).
      priorWork: d.prior_work_line || "",
      novelty: normNovelty(d.novelty),
      noveltyLine: d.novelty_line || "",
    })),
  };
}

// A bet in the ledger is fresher than the map: its verdict, odds and dates win.
// A node links to bets by id ("bets": [...]); failing that, by direction id within the same program.
export function joinBets(programs, bets) {
  for (const p of programs) {
    for (const d of p.directions) {
      const ids = [].concat(d.raw.bets || d.raw.bet || []).map(String);
      const b = ids.length ? bets.find((x) => x.id === ids[0])
        : bets.find((x) => (!x.program || x.program === p.id) && x.direction !== "" && String(x.direction) === d.id);
      if (!b) continue;
      d.bet = b;
      d.status = b.status;
      if (b.engine != null) d.engine = b.engine;
      if (b.human != null) d.human = b.human;
      if (b.diagnosis) d.diagnosis = b.diagnosis;
      if (b.result) d.result = b.result;
      if (b.cost) d.cost = b.cost;
      if (!d.opened) d.opened = b.opened || "";
      if (b.landed && b.status !== "open" && b.status !== "running") d.resolved = b.landed;
      if (b.novelty) { d.novelty = b.novelty; d.noveltyLine = b.noveltyLine || d.noveltyLine; }   // the ledger's line wins (rule 13)
      if (b.priorWork && !d.priorWork) d.priorWork = b.priorWork;
    }
  }
  return programs;
}

// A committed human-odds entry fills a direction's human odds. The first entry wins: it is the one given
// before any later look at the engine's number.
export function joinHumanOdds(programs, entries) {
  const first = new Map();
  for (const e of [...entries].sort((a, b) => String(a.recorded).localeCompare(String(b.recorded)))) {
    const k = `${e.program}|${e.direction}`;
    if (!first.has(k)) first.set(k, e);
  }
  for (const p of programs) for (const d of p.directions) {
    const e = first.get(`${p.id}|${d.id}`);
    if (e && d.human == null) { d.human = num(e.human_odds); d.humanEntry = e; }
  }
  return programs;
}

// What the cockpit asks next: per program, its open directions with no bet yet, not carried into another program,
// not waiting on an opens_when condition and not parked, in the map's own rank order (unranked last, then map
// order), skipping any already answered in ledger/human-odds.jsonl. Programs take turns, top of each map first.
export function nextToAsk(programs, answered = new Set(), max = 12) {
  const queues = programs.map((p) => p.directions
    .map((d, i) => ({ d, i }))
    .filter(({ d }) => d.status === "open" && !d.bet && !d.raw.moved_to && !d.raw.opens_when && !d.raw.parked
      && d.raw.status !== "parked" && !answered.has(`${p.id}|${d.id}`))
    .sort((a, b) => (a.d.raw.rank ?? Infinity) - (b.d.raw.rank ?? Infinity) || a.i - b.i)
    .map(({ d }, n) => ({ p, d, place: n + 1 })));
  const out = [];
  for (let round = 0; out.length < max && queues.some((q) => q.length > round); round++)
    for (const q of queues) if (q[round] && out.length < max) out.push(q[round]);
  return out;
}

// The engine's odds on a path that is still open stay hidden until the human has given theirs, so the public
// pages cannot anchor the human before the cockpit asks. Once a bet lands, or the human's odds are in, they show.
export function engineOddsVisible(d) {
  const open = d.status === "open" || d.status === "running";
  return !open || d.human != null;
}

// Kills come from three places; nothing is dropped, duplicates are merged.
export async function loadKills() {
  // ledger/kills.jsonl is optional. Ask for it only when the deploy copied it (the manifest lists the ledger's
  // files), so the kill log does not log a 404 on every load.
  const m = await manifest();
  const hasKills = !Array.isArray(m.ledger) || m.ledger.includes("kills.jsonl");
  const [explicit, bets, maps] = await Promise.all([
    hasKills ? getJSONL(DATA + "ledger/kills.jsonl") : null, loadBets(), loadMaps(),
  ]);
  joinBets(maps, bets);
  const out = [];
  const seen = new Map();
  const add = (k) => {
    const key = (k.key ? `bet|${k.key}` : `${k.program}|${k.direction || k.title}`).toLowerCase();
    if (seen.has(key)) {
      const prev = seen.get(key);
      for (const f of ["diagnosis", "evidence", "date", "title", "prereg"]) if (!prev[f] && k[f]) prev[f] = k[f];
      return;
    }
    seen.set(key, k);
    out.push(k);
  };
  for (const k of explicit || []) add({
    program: k.program || "", direction: String(k.direction ?? k.id ?? ""), title: k.title || k.direction || "",
    diagnosis: k.diagnosis || k.why || "", evidence: k.evidence || "", date: k.date || "", prereg: k.prereg_commit || "",
  });
  for (const p of maps) for (const d of p.directions) if (d.status === "killed") add({
    program: p.id, programTitle: p.title, direction: d.id, title: d.title, diagnosis: d.diagnosis,
    evidence: d.result || "", date: d.resolved || "", prereg: d.bet?.prereg || "", bet: d.bet || null,
    key: d.bet ? d.bet.id : null,
  });
  for (const b of bets) if (b.status === "killed") add({
    program: b.program, direction: String(b.direction || b.id), title: b.title, diagnosis: b.diagnosis,
    evidence: b.result, date: b.landed || b.date, prereg: b.prereg, bet: b, key: b.id,
  });
  for (const k of out) k.programTitle = k.programTitle || programTitle(k.program, maps);
  return out;
}
